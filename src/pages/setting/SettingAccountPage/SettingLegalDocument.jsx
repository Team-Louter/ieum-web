function SettingLegalDocument({ type }) {
  const document = legalDocuments[type];
  if (!document) return null;

  return (
    <article className="setting-legal-document">
      {document.sections.map((section) => (
        <section className="setting-legal-document__section" key={section.heading}>
          <h3>{section.heading}</h3>
          {section.paragraphs?.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
          {section.items && (
            <ul>
              {section.items.map((item) => <li key={item}>{item}</li>)}
            </ul>
          )}
          {section.links?.map((link) => (
            <a key={link.href} href={link.href} target="_blank" rel="noreferrer">
              {link.label}
            </a>
          ))}
        </section>
      ))}
      <p className="setting-legal-document__effective-date">{document.effectiveDate}</p>
    </article>
  );
}

export default SettingLegalDocument;
